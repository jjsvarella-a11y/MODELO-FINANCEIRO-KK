"""Single source for scenario seller cash flows; unreceived capital never becomes seller income."""
def seller_updates(items,pr):
 from xlsxwriter.utility import xl_col_to_name as col
 pv=lambda k:"'Pressupostos'!$B$"+str(pr[k]);u={'Vet Cenarios':{},'Resultados Cenarios':{}}
 for si,item in enumerate(items):
  sr=item['row'];fs=item['flow'];hs=item['hotel'];vc=si*4+1;ret=f"'Resultados Cenarios'!$B${sr}*{pv('received_ratio')}*(1-{pv('treasury_ratio')})";share=f"(1-'Resultados Cenarios'!$E${sr})"
  exit={}
  for h in [120,180]:
   en=h+4;exit[h]=f"MAX(0,SUM('{hs}'!T{en-11}:T{en})*{pv('exit_mult')}*(1-{pv('exit_cost')})-'{fs}'!AB{en}-'{fs}'!AX{en}+'{fs}'!AE{en}-'{fs}'!AP{en}-'{fs}'!AQ{en})"
  u['Resultados Cenarios'][f'X{sr}']=f"(T{sr}+Z{sr})*(1-E{sr})+({ret})+SUM('{fs}'!AV5:AW184)+'{fs}'!AX184"
  for m in range(181):
   r=m+5;fr=m+4;weight='+'.join(f'IF(A{r}={pv("fund_month"+str(j))},{pv("fund_part"+str(j))},0)' for j in [1,2,3])
   for j,h in [(2,120),(3,180)]:
    f='-'+pv('historic') if m==0 else '0' if m>h else f"'{fs}'!AD{fr}*{share}+({ret})*({weight})+'{fs}'!AV{fr}+'{fs}'!AW{fr}"
    if m==h:f+=f"+({exit[h]})*{share}+'{fs}'!AX{fr}"
    u['Vet Cenarios'][f'{col(vc+j)}{r}']=f
 return u
